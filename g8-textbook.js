function fractionalPart(a,b) { return rational(a-Math.floor(a/b)*b,b); }
function rationalTask(a,b,findPart) {
 const result=findPart?fractionalPart(a,b):Math.floor(a/b);
 const lower=Math.floor(a/b);
 return number(`Найди ${findPart?'дробную':'целую'} часть числа ${fraction(a,b)}.`,result,
  `Число не меньше ${integer(lower)} и меньше ${integer(lower+1)}. Целая часть — ${integer(lower)}. Дробная часть равна разности числа и его целой части.`);
}

function decomposition(m,n,a,b) {
 const first=shift(a),second=shift(b);
 return {first,second,expression:frac(linear(m+n,-m*b-n*a),`(${first})(${second})`),m,n,a,b};
}
function decompositionTask(m,n,a,b,target) {
 const {first,second,expression}=decomposition(m,n,a,b);
 const value=target==='A'?m:n,at=target==='A'?a:b;
 return number(`При допустимых x выполни разложение: ${expression} = ${frac('A',first)} + ${frac('B',second)}. Найди ${target}.`,value,
  `Умножаем на (${first})(${second}). Получаем равенство числителей. В это равенство подставляем x = ${integer(at)}: одно слагаемое исчезает, из другого получаем ${target} = ${integer(value)}.`);
}

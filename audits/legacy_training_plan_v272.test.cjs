'use strict';
const assert=require('node:assert/strict');
const {trainingPlanActions}=require('../assets/ui/legacy-vue-actions.js');
const keys=['back','earlier','later','toggle','remove','start','rebuild','delete','launch','complete'];
let active=true,blocked=false;
const calls=[];
const original=Object.fromEntries(keys.map(key=>[key,(id)=>{calls.push([key,id]);return key+':ok'}]));
original.unexpected=()=>{throw Error('Unapproved callback must not be exported');};
const actions=trainingPlanActions({isCurrent:()=>active,isBlocked:()=>blocked,actions:original});
assert.deepEqual(Object.keys(actions),keys);
assert.equal(actions.unexpected,undefined);
for(const key of keys)assert.equal(actions[key]('item-1'),key+':ok');
assert.deepEqual(calls,keys.map(key=>[key,'item-1']));
blocked=true;for(const key of keys)actions[key]('blocked');
assert.equal(calls.length,10,'Confirmation overlay must block all plan actions');
blocked=false;active=false;for(const key of keys)actions[key]('stale');
assert.equal(calls.length,10,'Detached plan must not mutate a profile');
active=true;
const fresh=trainingPlanActions({isCurrent:()=>active,actions:{back:()=>42,launch:()=>12}});
assert.notStrictEqual(fresh,actions,'Each mount needs independent callbacks');
assert.deepEqual(Object.keys(fresh),['back','launch']);
assert.equal(fresh.back(),42);assert.equal(fresh.launch(),12);
assert.equal(fresh.delete,undefined);
assert.equal([].toString.call(actions),'[object Object]');
console.log('PASS_V272_TRAINING_PLAN_ACTIONS editor/student/guards/unknown-key/fresh-mount');

'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const path=require('node:path');
const fs=require('node:fs');
const file='file://'+path.resolve('index.html');
async function main(){
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 let fails=0;
 try{
 for(const width of [320,390,768]){
  const context=await browser.newContext({viewport:{width,height:760},isMobile:width<500,hasTouch:width<500,acceptDownloads:true});
  const page=await context.newPage();
  page.on('dialog',d=>d.accept());
  try{
   await page.goto(file,{waitUntil:'domcontentloaded'});
   const setup=await page.evaluate(()=>{
    const a=ensureProfileIdentity({...EMPTY_STATE,xp:492,coins:101});
    const b=ensureProfileIdentity({...EMPTY_STATE,xp:783,coins:509});
    const data={'Проба A':a,'Проба B':b};
    localStorage.setItem('mq4_profiles',JSON.stringify(data));
    localStorage.setItem('mq4_current_profile','Проба A');
    localStorage.setItem('mq4',JSON.stringify(a));
    return data;
   });
   await page.reload({waitUntil:'domcontentloaded'});
   const corrupt='VERY_BAD_JSON[still valuable for forensic recovery]';
   await page.evaluate(raw=>localStorage.setItem('mq4_profiles',raw),corrupt);
   await page.reload({waitUntil:'domcontentloaded'});
   await page.waitForTimeout(70);
   const before=await page.evaluate(()=>({
    guard:mkV877CorruptProfiles,
    warning:!!document.getElementById('mk-v877-storage-recovery'),
    download:!!document.querySelector('#mk-v877-storage-recovery-actions'),
    original:localStorage.getItem('mq4_profiles'),
    fallbackCoins:state.coins,
    restoration:typeof mkV877AuthorizeExplicitRecovery
   }));
   assert(before.guard&&before.warning&&before.download,'Recovery banner missing '+JSON.stringify(before));
   assert.equal(before.original,corrupt);
   assert.equal(before.fallbackCoins,101);
   // file:// Chromium sometimes blocks the download event; inspect the actual Blob content,
   // filename and export flag generated by the button without relying on browser download UI.
   const generated=await page.evaluate(()=>{
    const BlobOriginal=window.Blob,clickOriginal=HTMLAnchorElement.prototype.click;
    let raw=null,name=null;
    window.Blob=function(parts,opts){raw=parts.map(String).join('');return new BlobOriginal(parts,opts)};
    HTMLAnchorElement.prototype.click=function(){name=this.download};
    try{
      document.querySelector('#mk-v877-storage-recovery button').click();
      return {raw,name,exported:mkV877RecoveryExported};
    }finally{window.Blob=BlobOriginal;HTMLAnchorElement.prototype.click=clickOriginal}
   });
   assert.equal(generated.name,'matkvest_corrupt_profiles_rescue.txt');
   assert.equal(generated.raw,corrupt,'Exported Blob differs from corrupt original');
   assert(generated.exported,'User export flag missing');

   // Explicit full-backup restore (only after user-triggered Replace confirmation).
   const recovered=await page.evaluate(data=>{
     pendingImport={profiles:data,currentProfile:'Проба A'};
     replaceWithPendingImport();
     return {guard:mkV877CorruptProfiles,
      raw:localStorage.getItem('mq4_profiles'),
      rescue:localStorage.getItem('mk_v877_corrupt_profiles_rescue'),
      banner:!!document.getElementById('mk-v877-storage-recovery'),
      active:currentProfile,coins:state.coins,
      names:Object.keys(profiles).sort()};
   },setup);
   assert.equal(recovered.guard,false);
   assert.equal(recovered.banner,false);
   assert.equal(recovered.rescue,corrupt,'Original corrupt document not backed up');
   assert.equal(recovered.active,'Проба A');
   assert.equal(recovered.coins,101);
   assert.deepEqual(recovered.names,['Проба A','Проба B']);
   await page.reload({waitUntil:'domcontentloaded'});
   const final=await page.evaluate(()=>({
    guard:mkV877CorruptProfiles,active:currentProfile,
    names:Object.keys(profiles).sort(),A:profiles['Проба A']?.coins,B:profiles['Проба B']?.coins,
    rescue:localStorage.getItem('mk_v877_corrupt_profiles_rescue')
   }));
   assert.equal(final.guard,false);
   assert.equal(final.rescue,corrupt);
   assert.equal(final.A,101);
   assert.equal(final.B,509);
   console.log('PASS_STAGE26_RECOVERY',JSON.stringify({width,before,recovered:{...recovered,raw:'<omitted>'},final}));
  }catch(e){fails++;console.error('FAIL_STAGE26_RECOVERY',JSON.stringify({width,error:String(e),stack:String(e.stack||'').slice(0,1300)}))}
  await context.close();
 }
 }finally{await browser.close()}
 console.log('STAGE26_RECOVERY_SUMMARY',JSON.stringify({expected:3,failures:fails}));
 if(fails)process.exitCode=1;
}
main().catch(e=>{console.error(e);process.exitCode=1});
